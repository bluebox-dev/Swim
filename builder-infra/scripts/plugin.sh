#!/usr/bin/env bash
# Manage optional plugins: which ones are linked into the server and the agent.
#
#   plugin.sh list                     plugins in plugins/, and which are enabled
#   plugin.sh enable <name>            link the plugin in, rebuild server + agent
#   plugin.sh disable <name>           take it out again, rebuild server + agent (its data stays)
#   plugin.sh disable <name> --purge   …and delete its tables and files for good
#   plugin.sh gen                      only rewrite the generated import files (used by the build scripts)
#
# A plugin is compiled in, not loaded at run time: a disabled plugin is not in the server
# binary, not in the agent, and its web files are not served. Add --no-build to enable/disable
# to change the list without rebuilding (then run it again without the flag, or rebuild yourself).
# Run on the server from anywhere; needs sudo for docker.
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd); ROOT=$(cd "$HERE/.." && pwd)
LIST=$ROOT/plugins/enabled
SERVER_GEN=$ROOT/backend/cmd/server/plugins_gen.go
AGENT_GEN=$ROOT/agent/cmd/swim-agent/plugins_gen.go
DATA=${SWIM_DATA:-/srv/swim}

enabled() { [ -f "$LIST" ] && grep -vE '^\s*(#|$)' "$LIST" | tr -d ' \r' || true; }
valid()   { [[ "$1" =~ ^[a-z][a-z0-9-]{1,30}$ ]] && [ -d "$ROOT/plugins/$1" ]; }
psql()    { sudo docker exec -i swim-postgres-1 psql -U swim_owner -d swim -At "$@"; }

gen() { # the two files that decide what is linked in; no plugins = no files
  local srv="" agt="" n
  for n in $(enabled); do
    valid "$n" || { echo "plugins/enabled names '$n', but plugins/$n does not exist" >&2; exit 1; }
    [ -d "$ROOT/plugins/$n/server" ] && srv+="	_ \"swim/plugins/$n/server\""$'\n'
    [ -d "$ROOT/plugins/$n/agent" ]  && agt+="	_ \"swim/plugins/$n/agent\""$'\n'
  done
  write() { # file, imports
    if [ -z "$2" ]; then rm -f "$1"; return; fi
    printf '// Code generated by builder-infra/scripts/plugin.sh from plugins/enabled. DO NOT EDIT.\n\npackage main\n\nimport (\n%s)\n' "$2" > "$1"
  }
  write "$SERVER_GEN" "$srv"; write "$AGENT_GEN" "$agt"
}

rebuild() {
  [ "${NO_BUILD:-}" = 1 ] && { echo "list changed; nothing rebuilt (--no-build)"; return; }
  # machines only fetch a new agent when its version number is higher: step the patch number
  local f=$ROOT/agent/internal/agent/state.go v maj min pat
  v=$(grep -E '^const Version' "$f" | cut -d'"' -f2); IFS=. read -r maj min pat <<<"$v"
  sudo sed -i "s/^const Version = \"$v\"/const Version = \"$maj.$min.$((pat + 1))\"/" "$f"
  echo "== agent $v -> $maj.$min.$((pat + 1)) (so machines update themselves)"
  echo "== server"
  (cd "$HERE" && sudo docker compose build backend && sudo docker compose up -d --no-deps backend)
  echo "== agent"
  bash "$HERE/scripts/build-agent.sh"
  sudo docker exec swim-nginx-1 nginx -s reload >/dev/null 2>&1 || true
}

cmd=${1:-list}; name=${2:-}; shift $(( $# > 2 ? 2 : $# )) || true
for a in "$@"; do case "$a" in --no-build) NO_BUILD=1 ;; --purge) PURGE=1 ;; esac; done

case "$cmd" in
  list)
    for d in "$ROOT"/plugins/*/; do
      n=$(basename "$d"); [ -f "$d/plugin.json" ] || continue
      state="disabled"; enabled | grep -qx "$n" && state="enabled"
      printf '%-12s %-9s %s\n' "$n" "$state" "$(grep -o '"description": *"[^"]*"' "$d/plugin.json" | cut -d'"' -f4)"
    done ;;
  gen) gen ;;
  enable)
    valid "$name" || { echo "no such plugin: $name (see plugin.sh list)" >&2; exit 1; }
    enabled | grep -qx "$name" && { echo "$name is already enabled"; exit 0; }
    [ -f "$LIST" ] || sudo cp "$ROOT/plugins/enabled.example" "$LIST"
    echo "$name" | sudo tee -a "$LIST" >/dev/null
    sudo mkdir -p "$DATA/plugins/$name" && sudo chmod 750 "$DATA/plugins/$name"
    sudo -E bash "$0" gen; rebuild
    echo "plugin $name enabled" ;;
  disable)
    enabled | grep -qx "$name" || { echo "$name is not enabled"; exit 0; }
    # a plugin that changed machines must be switched off on them first: once it is out of the
    # agent, nothing can undo what it set there
    check=$(grep -o '"active_check": *"[^"]*"' "$ROOT/plugins/$name/plugin.json" 2>/dev/null | cut -d'"' -f4 || true)
    if [ -n "$check" ]; then
      n=$(psql -c "$check" 2>/dev/null || echo 0)
      [ "${n:-0}" = 0 ] || { echo "$n machine(s) still have $name switched on — switch it off in the console first" >&2; exit 1; }
    fi
    sudo sed -i "/^\s*$name\s*$/d" "$LIST"
    sudo -E bash "$0" gen; rebuild
    if [ "${PURGE:-}" = 1 ]; then
      tables=$(grep -o '"tables": *\[[^]]*\]' "$ROOT/plugins/$name/plugin.json" | grep -o '"[a-z_]*"' | tr -d '"' | grep -v '^tables$' | paste -sd, -)
      [ -n "$tables" ] && psql -c "DROP TABLE IF EXISTS $tables CASCADE; DELETE FROM schema_migrations WHERE version LIKE '${name}\\_%'" >/dev/null
      sudo rm -rf "${DATA:?}/plugins/$name"
      echo "plugin $name disabled; its tables ($tables) and files are deleted"
    else
      echo "plugin $name disabled; its data is kept (add --purge to delete it)"
    fi ;;
  *) sed -n '2,12p' "$0"; exit 2 ;;
esac
